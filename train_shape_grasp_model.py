#!/usr/bin/env python3
"""Train and evaluate numerical-only grasp selection on shape-family Drake trials.

Usage:
  python train_shape_grasp_model.py grasp_dataset/shape_families/<run>/trials.csv

Requires: numpy, pandas, scikit-learn (pip install scikit-learn pandas numpy).
Each geometry's candidate grasps are kept in the same train/test partition.
No vessel names or shape-family labels are used as model features.
"""
import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, balanced_accuracy_score, roc_auc_score


CANDIDATE_FEATURES = [
    'height_m', 'mass_kg', 'com_height_m', 'max_diameter_m',
    'grasp_fraction', 'grasp_height_m', 'local_radius_m',
    'local_slope_dr_dz', 'grasp_minus_com_m', 'grasp_minus_com_over_height',
    'local_diameter_over_max_diameter', 'radius_below_10mm_m',
    'radius_above_10mm_m', 'slope_below_10mm', 'slope_above_10mm',
    'base_radius_m', 'mouth_radius_m', 'height_over_max_diameter',
]


def profile_at(profile, height, z_m):
    z_fraction = float(np.clip(z_m / height, 0, 1))
    for (za, ra), (zb, rb) in zip(profile[:-1], profile[1:]):
        if z_fraction <= zb + 1e-10:
            t = float(np.clip((z_fraction - za) / (zb - za), 0, 1))
            return ra + t * (rb - ra), (rb - ra) / ((zb - za) * height)
    return profile[-1][1], 0.0


def add_features(df, settings):
    profiles = settings['profiles']
    rows = []
    for r in df.itertuples(index=False):
        # 'shape_family' is used ONLY to reconstruct the actual numeric radius
        # profile from the experiment snapshot; it is NOT a model input.
        # New diversified datasets store the exact numerical radius profile
        # for each individual vessel. Older datasets use the family template.
        per_geometry = settings.get('geometry_profiles', {})
        if r.geometry_id in per_geometry:
            profile = [(float(z), float(rad))
                       for z, rad in per_geometry[r.geometry_id]]
        else:
            profile = [(float(z), float(rad) * float(r.radius_scale))
                       for z, rad in profiles[r.shape_family]]
        z = float(r.grasp_height_m)
        h = float(r.height_m)
        rad_lo, slope_lo = profile_at(profile, h, z - 0.01)
        rad_hi, slope_hi = profile_at(profile, h, z + 0.01)
        com_gap = z - float(r.com_height_m)
        rows.append({
            'grasp_minus_com_m': com_gap,
            'grasp_minus_com_over_height': com_gap / h,
            'local_diameter_over_max_diameter': 2 * float(r.local_radius_m) / float(r.max_diameter_m),
            'radius_below_10mm_m': rad_lo,
            'radius_above_10mm_m': rad_hi,
            'slope_below_10mm': slope_lo,
            'slope_above_10mm': slope_hi,
            'base_radius_m': profile[0][1],
            'mouth_radius_m': profile[-1][1],
            'height_over_max_diameter': h / float(r.max_diameter_m),
        })
    return pd.concat([df.reset_index(drop=True), pd.DataFrame(rows)], axis=1)


def make_model(seed):
    return RandomForestClassifier(
        n_estimators=350,
        min_samples_leaf=2,
        max_features=0.8,
        class_weight='balanced_subsample',
        random_state=seed,
        n_jobs=-1,
    )


def choose_one_per_scenario(frame, score_column):
    # One vessel geometry + source position is one grasp selection problem.
    # Stable sort ensures repeatable ties, independent of dataframe ordering.
    picked = frame.sort_values(['geometry_id', 'position_index', score_column, 'grasp_fraction'],
                               ascending=[True, True, False, True], kind='mergesort')
    return picked.drop_duplicates(['geometry_id', 'position_index'])


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('csv_path', type=Path, help='trials.csv generated by the shape grasp collector')
    ap.add_argument('--seed', type=int, default=4210)
    ap.add_argument('--output-dir', type=Path, default=None)
    args = ap.parse_args()

    csv_path = args.csv_path.expanduser().resolve()
    settings_path = csv_path.parent / 'settings.json'
    if not csv_path.is_file() or not settings_path.is_file():
        ap.error('Expected an existing trials.csv and settings.json in the same directory')

    df = pd.read_csv(csv_path)
    settings = json.loads(settings_path.read_text())
    expected = set(['shape_family', 'geometry_id', 'geometry_index', 'position_index',
                    'grasp_fraction', 'stable_grasp_success', 'failure_reason',
                    'radius_scale'] + CANDIDATE_FEATURES[:8])
    missing = sorted(expected - set(df.columns))
    if missing:
        ap.error(f'Missing required CSV columns: {missing}')

    # Simulator errors do not mean a physically unsuccessful grasp. Omit these
    # from both classifier training and reported candidate-selection scores.
    invalid = {'simulation_error', 'timeout', 'missing_summary', 'missing_upright_metric'}
    removed = df['failure_reason'].isin(invalid).sum()
    df = df.loc[~df['failure_reason'].isin(invalid)].copy()
    df = add_features(df, settings)
    df['target'] = df['stable_grasp_success'].astype(str).str.lower().eq('true').astype(int)
    if df['geometry_id'].nunique() < 3:
        ap.error('At least 3 distinct generated geometries are required')

    for f in CANDIDATE_FEATURES:
        df[f] = pd.to_numeric(df[f], errors='coerce')
    good = df[CANDIDATE_FEATURES].notna().all(axis=1)
    if not good.all():
        print(f'Dropping {(~good).sum()} rows with missing geometry features')
        df = df.loc[good].copy()

    # Three randomized geometries per family: hold out geometry index 0, 1, or
    # 2 in turn. This tests unseen dimension/mass variations from every family.
    # Crucially, every grasp for a geometry stays in its holdout fold.
    geom_indices = sorted(df['geometry_index'].unique())
    if len(geom_indices) < 3:
        ap.error('Need >=3 geometry indices (rerun collector with --scales 3 or more)')

    outdir = args.output_dir or (csv_path.parent / 'model_evaluation')
    outdir.mkdir(parents=True, exist_ok=True)
    all_rows = []
    fold_summaries = []

    print(f'Loaded {len(df)} valid trials from {df.geometry_id.nunique()} geometries; '
          f'{removed} simulator-error rows excluded')
    print('Model features: ' + ', '.join(CANDIDATE_FEATURES))
    print('Shape names, vessel IDs and observed contact results are NOT model inputs.\n')

    for fold_index in geom_indices:
        is_test = df['geometry_index'].eq(fold_index)
        train = df.loc[~is_test].copy()
        test = df.loc[is_test].copy()
        # Guard against IDs shared between train and test, including different positions.
        assert not set(train.geometry_id).intersection(test.geometry_id)
        if train.target.nunique() != 2:
            print(f'Skipping fold {fold_index}: training data lacks both classes')
            continue
        model = make_model(args.seed + int(fold_index))
        model.fit(train[CANDIDATE_FEATURES], train['target'])
        test['predicted_success_probability'] = model.predict_proba(test[CANDIDATE_FEATURES])[:, 1]
        test['predicted_label'] = (test.predicted_success_probability >= 0.5).astype(int)

        # Fair fixed-fraction baseline: select the best fraction ONLY on the
        # training set; evaluate that same fraction on held-out geometries.
        fraction_success = train.groupby('grasp_fraction')['target'].mean()
        selected_frac = float(fraction_success.idxmax())
        test['fixed_baseline_score'] = -abs(test['grasp_fraction'] - selected_frac)
        model_choices = choose_one_per_scenario(test, 'predicted_success_probability')
        fixed_choices = choose_one_per_scenario(test, 'fixed_baseline_score')
        oracle = test.groupby(['geometry_id', 'position_index'])['target'].max()
        n_scenarios = len(oracle)
        rf_hits = int(model_choices.target.sum())
        baseline_hits = int(fixed_choices.target.sum())
        oracle_hits = int(oracle.sum())
        fold_summaries.append(dict(fold=int(fold_index), scenarios=n_scenarios,
                                   model_success=rf_hits, fixed_success=baseline_hits,
                                   oracle_success=oracle_hits, fixed_fraction=selected_frac,
                                   classification_accuracy=float(accuracy_score(test.target, test.predicted_label)),
                                   balanced_accuracy=float(balanced_accuracy_score(test.target, test.predicted_label)),
                                   roc_auc=float(roc_auc_score(test.target, test.predicted_success_probability))
                                   if test.target.nunique() == 2 else None))
        print(f'Holdout geometry index {fold_index}: model {rf_hits}/{n_scenarios}, '
              f'fixed {baseline_hits}/{n_scenarios}, oracle {oracle_hits}/{n_scenarios}; '
              f'fixed fraction learned on training set={selected_frac:.2f}')
        test['fold'] = fold_index
        test['selected_by_model'] = test.index.isin(model_choices.index)
        test['selected_by_fixed'] = test.index.isin(fixed_choices.index)
        all_rows.append(test)

    if not all_rows:
        ap.error('No folds could be trained')
    predictions = pd.concat(all_rows).sort_values(['shape_family', 'geometry_index', 'position_index', 'grasp_fraction'])
    predictions.to_csv(outdir / 'heldout_predictions.csv', index=False)
    pd.DataFrame(fold_summaries).to_csv(outdir / 'fold_scores.csv', index=False)
    metrics = {k: int(sum(s[k] for s in fold_summaries))
               for k in ['scenarios', 'model_success', 'fixed_success', 'oracle_success']}
    metrics['model_success_rate'] = metrics['model_success'] / metrics['scenarios']
    metrics['fixed_success_rate'] = metrics['fixed_success'] / metrics['scenarios']
    metrics['oracle_success_rate'] = metrics['oracle_success'] / metrics['scenarios']
    metrics['features'] = CANDIDATE_FEATURES
    metrics['note'] = ('Oracle is the best among sampled candidate heights, not physically optimal. '
                       'These are small, same-family holdouts; no evidence yet of transfer to an unseen shape family.')
    (outdir / 'summary.json').write_text(json.dumps(metrics, indent=2) + '\n')

    print('\nHELD-OUT GRASP SELECTION')
    for label, key in [('Random forest', 'model_success'), ('Training-selected fixed fraction', 'fixed_success'),
                       ('Sampled-height oracle', 'oracle_success')]:
        print(f'  {label}: {metrics[key]}/{metrics["scenarios"]} '
              f'({100 * metrics[key] / metrics["scenarios"]:.1f}%)')
    print(f'\nSaved results to: {outdir}')
    print('Note: Results are on new geometries within known shape families; '
          'a leave-one-family-out evaluation is a harder follow-up.')


if __name__ == '__main__':
    main()
